//! `cargo xtask budgets [--check|--write]`: validates `perf/budgets.toml` and
//! keeps the budget table in `PERFORMANCE.md` in sync with it (#20).

use std::collections::HashSet;
use std::fmt::Write as _;

use serde::Deserialize;

const BUDGETS: &str = "perf/budgets.toml";
const DOC: &str = "PERFORMANCE.md";
const START: &str = "<!-- budgets:start (generated by `cargo xtask budgets --write`) -->";
const END: &str = "<!-- budgets:end -->";

const CLASSES: &[&str] = &["deterministic", "timing", "resource"];
const GATES: &[&str] = &[
    "pr-strict",
    "pr-ab",
    "nightly-ab",
    "nightly-trend",
    "report-only",
];
const STATUSES: &[&str] = &["provisional", "calibrated"];
const BOUNDS: &[&str] = &["max", "min"];
const ARCHES: &[&str] = &["x86_64", "aarch64"];

/// The whole file.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Budgets {
    /// One entry per budget row.
    pub budget: Vec<Budget>,
}

/// One budget row.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Budget {
    /// Stable identifier, for example `engine.ready.warm`.
    pub id: String,
    /// What is measured.
    pub metric: String,
    /// Unit of `limit`.
    pub unit: String,
    /// `max` or `min`.
    pub bound: String,
    /// The number; absent while an issue still has to set it.
    pub limit: Option<f64>,
    /// Metric class.
    pub class: String,
    /// Where it is gated.
    pub gate: String,
    /// `provisional` or `calibrated`.
    pub status: String,
    /// Decision or issue the number comes from.
    pub source: String,
    /// Named workload.
    pub workload: String,
    /// Tool and API used.
    pub how: String,
    /// Architectures the row applies to.
    pub arch: Vec<String>,
}

pub fn run(mode: Option<&str>) -> Result<String, String> {
    let toml_text = std::fs::read_to_string(BUDGETS).map_err(|e| format!("{BUDGETS}: {e}"))?;
    let budgets = parse(&toml_text)?;
    let doc = std::fs::read_to_string(DOC).map_err(|e| format!("{DOC}: {e}"))?;
    let updated = splice(&doc, &render(&budgets))?;
    match mode {
        Some("--write") => {
            std::fs::write(DOC, &updated).map_err(|e| format!("{DOC}: {e}"))?;
            Ok(format!(
                "budgets: wrote {} rows into {DOC}",
                budgets.budget.len()
            ))
        }
        Some("--check") | None => {
            if updated == doc {
                Ok(format!(
                    "budgets: ok ({} rows, {DOC} in sync)",
                    budgets.budget.len()
                ))
            } else {
                Err(format!(
                    "budgets: the table in {DOC} differs from {BUDGETS}; run `cargo xtask budgets --write`"
                ))
            }
        }
        Some(other) => Err(format!("budgets: unknown option {other}")),
    }
}

/// Parses and validates the TOML text.
pub fn parse(text: &str) -> Result<Budgets, String> {
    let budgets: Budgets = toml::from_str(text).map_err(|e| format!("{BUDGETS}: {e}"))?;
    let mut problems = Vec::new();
    let mut seen = HashSet::new();
    for row in &budgets.budget {
        let id = &row.id;
        if !seen.insert(id.as_str()) {
            problems.push(format!("duplicate id {id}"));
        }
        for (field, value, allowed) in [
            ("class", &row.class, CLASSES),
            ("gate", &row.gate, GATES),
            ("status", &row.status, STATUSES),
            ("bound", &row.bound, BOUNDS),
        ] {
            if !allowed.contains(&value.as_str()) {
                problems.push(format!("{id}: unknown {field} `{value}`"));
            }
        }
        for (field, value) in [
            ("source", &row.source),
            ("metric", &row.metric),
            ("unit", &row.unit),
            ("workload", &row.workload),
            ("how", &row.how),
        ] {
            if value.trim().is_empty() {
                problems.push(format!("{id}: empty {field}"));
            }
        }
        if row.arch.is_empty() || row.arch.iter().any(|a| !ARCHES.contains(&a.as_str())) {
            problems.push(format!(
                "{id}: arch must be a non-empty subset of {ARCHES:?}"
            ));
        }
        if row.limit.is_none() && row.status == "calibrated" {
            problems.push(format!("{id}: a calibrated row needs a limit"));
        }
    }
    if problems.is_empty() {
        Ok(budgets)
    } else {
        Err(format!(
            "{BUDGETS} is invalid:\n  {}",
            problems.join("\n  ")
        ))
    }
}

/// Renders the Markdown table.
pub fn render(budgets: &Budgets) -> String {
    let mut out = String::from(
        "| id | budget | class | gate | status | workload | how | source |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n",
    );
    for row in &budgets.budget {
        let op = if row.bound == "min" { ">=" } else { "<=" };
        let budget = row.limit.map_or_else(
            || "to be set".to_owned(),
            |limit| format!("{op} {limit} {}", row.unit),
        );
        let _ = writeln!(
            out,
            "| `{}` | {budget} | {} | {} | {} | {} | {} | {} |",
            row.id,
            row.class,
            row.gate,
            row.status,
            escape(&row.workload),
            escape(&row.how),
            escape(&row.source)
        );
    }
    out
}

fn escape(text: &str) -> String {
    text.replace('|', "\\|")
}

/// Replaces the text between the markers with `table`.
pub fn splice(doc: &str, table: &str) -> Result<String, String> {
    let start = doc
        .find(START)
        .ok_or_else(|| format!("{DOC}: start marker missing"))?;
    let after_start = start + START.len();
    let end = doc
        .get(after_start..)
        .and_then(|rest| rest.find(END))
        .map(|offset| after_start + offset)
        .ok_or_else(|| format!("{DOC}: end marker missing"))?;
    let head = doc.get(..after_start).unwrap_or_default();
    let tail = doc.get(end..).unwrap_or_default();
    Ok(format!("{head}\n\n{table}\n{tail}"))
}

#[cfg(test)]
mod tests {
    use super::{END, START, parse, render, splice};

    const ROW: &str = r#"
[[budget]]
id = "a.b"
metric = "m"
unit = "ms"
bound = "max"
limit = 1
class = "timing"
gate = "pr-ab"
status = "provisional"
source = "F7"
workload = "w"
how = "h"
arch = ["x86_64"]
"#;

    #[test]
    fn the_real_file_is_valid() {
        let text = std::fs::read_to_string("../perf/budgets.toml").unwrap();
        assert!(parse(&text).unwrap().budget.len() > 20);
    }

    #[test]
    fn accepts_a_valid_row() {
        assert_eq!(parse(ROW).unwrap().budget.len(), 1);
    }

    #[test]
    fn rejects_unknown_class_gate_and_status() {
        let bad = ROW
            .replace("\"timing\"", "\"fast\"")
            .replace("\"pr-ab\"", "\"sometimes\"")
            .replace("\"provisional\"", "\"maybe\"");
        let error = parse(&bad).unwrap_err();
        assert!(error.contains("unknown class"));
        assert!(error.contains("unknown gate"));
        assert!(error.contains("unknown status"));
    }

    #[test]
    fn rejects_duplicate_ids() {
        let error = parse(&format!("{ROW}{ROW}")).unwrap_err();
        assert!(error.contains("duplicate id a.b"));
    }

    #[test]
    fn rejects_a_row_without_source() {
        let without = ROW.replace("source = \"F7\"\n", "");
        assert!(parse(&without).is_err());
        let empty = ROW.replace("source = \"F7\"", "source = \" \"");
        assert!(parse(&empty).unwrap_err().contains("empty source"));
    }

    #[test]
    fn rejects_unknown_fields() {
        assert!(parse(&ROW.replace("how = \"h\"", "how = \"h\"\ncolour = \"red\"")).is_err());
    }

    #[test]
    fn splice_detects_drift() {
        let budgets = parse(ROW).unwrap();
        let table = render(&budgets);
        let doc = format!("intro\n{START}\n\nold table\n{END}\noutro\n");
        let updated = splice(&doc, &table).unwrap();
        assert_ne!(updated, doc);
        assert_eq!(splice(&updated, &table).unwrap(), updated);
        assert!(updated.contains("| `a.b` | <= 1 ms |"));
    }

    #[test]
    fn splice_needs_both_markers() {
        assert!(splice("no markers", "t").is_err());
        assert!(splice(&format!("{START} only"), "t").is_err());
    }
}
